#!/usr/bin/env bash
# One-time Postgres 16 -> 18 upgrade for a single staging app stack.
#
# Runs ON THE SERVER, driven by the Makefile:
#
#   make pg18-dump                    # MODE=dump for naikbusaja + maribelanja
#   make pg18-upgrade APP=naikbusaja  # MODE=upgrade, wipes that stack's pgdata
#   make pg18-upgrade APP=maribelanja
#
# A PG18 server cannot read a PG16 data directory, so the "upgrade" is a
# dump / wipe / re-init / restore. What carries over: the `users` table for
# both apps (password hashes travel with the rows, so logins keep working)
# and naikbusaja's `user_favorite_routes`. Everything else is disposable on
# staging: sessions (users_tokens) are skipped on purpose, maribelanja's
# catalog rows are dropped, and naikbusaja re-imports the transit feed on
# first boot.
#
#   MODE=dump    APP=<app>  -> save user rows to /opt/<app>/backups/ and
#                              record the path in /opt/<app>/.pg18-dump-path
#   MODE=upgrade APP=<app>  -> destructive: down -v, PG18 re-init, restore
#   FULL=1      (dump only) -> also pg_dump the whole database (can be very
#                              large for naikbusaja's transit tables)
set -euo pipefail

MODE=${MODE:?MODE=dump|upgrade}
APP=${APP:?APP=naikbusaja|maribelanja}

DB_NAME=; DB_USER=; TABLES=
case "$APP" in
  naikbusaja)
    # Compose pins postgres/postgres (no published port, internal network).
    DB_NAME=naikbusaja_prod
    DB_USER=postgres
    TABLES="users user_favorite_routes"
    ;;
  maribelanja)
    # Credentials live in the server-only .env generated by gen-secrets.sh.
    set -a; . /opt/maribelanja/.env; set +a
    DB_NAME=${POSTGRES_DB:-maribelanja}
    DB_USER=${POSTGRES_USER:-postgres}
    TABLES="users"
    ;;
  *) echo "unknown APP=$APP (expected naikbusaja or maribelanja)"; exit 1 ;;
esac

COMPOSE() { docker compose -f "/opt/$APP/docker-compose.staging.yml" "$@"; }
PSQL()    { COMPOSE exec -T db psql -U "$DB_USER" -d "$DB_NAME" -v ON_ERROR_STOP=1 "$@"; }

count_rows() { # count_rows <table> — row count (only call for tables that exist)
  COMPOSE exec -T db psql -U "$DB_USER" -d "$DB_NAME" -tAc \
    "SELECT COUNT(*) FROM public.$1" | tr -d '[:space:]'
}

dump() {
  local dir="/opt/$APP/backups" stamp file table
  stamp=$(date +%Y%m%d-%H%M%S)
  mkdir -p "$dir"

  echo "== $APP: dumping user tables from the running cluster =="
  for table in $TABLES; do
    echo "   $table: $(count_rows "$table") rows"
  done

  # --data-only keeps schema out of it; the fresh cluster gets its schema
  # from the app's own migrations. Rows keep their original ids.
  file="$dir/pg18-users-$stamp.sql"
  COMPOSE exec -T db pg_dump -U "$DB_USER" -d "$DB_NAME" --data-only \
    $(printf -- '--table=%s ' $TABLES) > "$file"
  [ -s "$file" ] || { echo "dump came out empty, aborting"; exit 1; }

  if [ "${FULL:-0}" = "1" ]; then
    echo "== $APP: full-database dump requested (may be large) =="
    COMPOSE exec -T db pg_dump -U "$DB_USER" -d "$DB_NAME" > "$dir/pg18-full-$stamp.sql"
    ls -lh "$dir/pg18-full-$stamp.sql"
  fi

  # The upgrade step refuses to run without this marker.
  { echo "$file"; for table in $TABLES; do echo "$table=$(count_rows "$table")"; done; } \
    > "/opt/$APP/.pg18-dump-path"
  chmod 600 "$file" "/opt/$APP/.pg18-dump-path"
  echo "   saved: $file ($(wc -c < "$file") bytes)"
}

wait_for_table() { # wait_for_table <table> <seconds> — poll until migrations created it
  local table=$1 deadline=$(( $(date +%s) + $2 ))
  until [ "$(COMPOSE exec -T db psql -U "$DB_USER" -d "$DB_NAME" -tAc \
            "SELECT to_regclass('public.$table') IS NOT NULL")" = "t" ]; do
    if [ "$(date +%s)" -ge "$deadline" ]; then
      echo "timed out waiting for '$table' — check: docker compose -f /opt/$APP/docker-compose.staging.yml logs app"
      exit 1
    fi
    sleep 3
  done
}

reset_sequence() { # reset_sequence <table> — next insert must not collide with restored ids
  COMPOSE exec -T db psql -U "$DB_USER" -d "$DB_NAME" -tAc \
    "SELECT setval(pg_get_serial_sequence('public.$1','id'), GREATEST((SELECT COALESCE(MAX(id),1) FROM public.$1), 1))"
}

upgrade() {
  local marker="/opt/$APP/.pg18-dump-path" dump_file table line want got
  [ -f "$marker" ] || { echo "no dump marker at $marker — run make pg18-dump first"; exit 1; }
  dump_file=$(head -n1 "$marker")
  [ -s "$dump_file" ] && grep -q '^COPY ' "$dump_file" \
    || { echo "dump file $dump_file is missing or has no COPY data — run make pg18-dump first"; exit 1; }

  # Refuse to wipe unless the synced compose file already points at PG18.
  grep -qE 'image: (postgres|postgis/postgis):18' "/opt/$APP/docker-compose.staging.yml" \
    || { echo "/opt/$APP/docker-compose.staging.yml is not on postgres 18 yet — make pg18-upgrade syncs it"; exit 1; }

  echo "== $APP: wiping the pgdata volume and re-initialising on PG18 =="
  echo "   restoring later from: $dump_file"
  COMPOSE down -v

  case "$APP" in
    maribelanja)
      # Schema comes from the one-shot migrate service; restore while the
      # app is still down.
      COMPOSE up -d --build migrate
      wait_for_table users 300
      ;;
    naikbusaja)
      # Migrations run inside the app entrypoint on first boot, so bring the
      # whole stack up and wait for the schema before restoring. The app is
      # briefly live with an empty users table — fine on staging.
      COMPOSE up -d --build
      wait_for_table users 300
      ;;
  esac

  echo "== $APP: restoring user rows =="
  for table in $TABLES; do
    want=$(grep -E "^$table=" "$marker" | cut -d= -f2)
    echo "   $table: expected $want rows"
  done
  PSQL < "$dump_file"

  for table in $TABLES; do reset_sequence "$table" >/dev/null; done

  case "$APP" in
    maribelanja) COMPOSE up -d ;; # app + mailpit (migrate re-runs as a no-op)
    naikbusaja)  echo "   app already up — transit feed re-imports on its own schedule" ;;
  esac

  echo "== $APP: post-upgrade checks =="
  COMPOSE exec -T db psql -U "$DB_USER" -d "$DB_NAME" -tAc "SHOW server_version"
  for table in $TABLES; do
    want=$(grep -E "^$table=" "$marker" | cut -d= -f2)
    got=$(count_rows "$table")
    if [ "$got" = "$want" ]; then
      echo "   ok: $table has $got rows"
    else
      echo "   MISMATCH: $table has $got rows, expected $want — inspect before moving on"
      exit 1
    fi
  done
  echo "   done — verify a login at https://$APP.darmawan.be (users_tokens was not restored, sessions start fresh)"
}

case "$MODE" in
  dump)    dump ;;
  upgrade) upgrade ;;
  *) echo "unknown MODE=$MODE (expected dump or upgrade)"; exit 1 ;;
esac
